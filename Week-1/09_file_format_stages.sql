CREATE OR REPLACE FILE FORMAT SALES_CSV_FORMAT
    TYPE = 'CSV'
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    NULL_IF = ('NULL', 'null', '');

CREATE STAGE STG_ECOMM
FILE_FORMAT = SALES_CSV_FORMAT;

CREATE OR REPLACE TABLE ECOMM_SALES(
DATE_OF_SALES STRING,
TOTAL_REVENUE STRING
);

COPY INTO ECOMM_SALES
FROM @STG_ECOMM
FILE_FORMAT = (FORMAT_NAME = SALES_CSV_FORMAT)
ON_ERROR = 'CONTINUE' ;
